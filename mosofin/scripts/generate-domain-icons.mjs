#!/usr/bin/env node

// Domain icons are business pictograms for nodes that have no brand mark: a
// supplier, a warehouse, a controller, a legal entity. They come from Lucide
// (ISC) so the artwork is a maintained, openly licensed icon set rather than
// anything drawn or traced here. They are never a vendor logo.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const catalogPath = path.join(root, 'domain-icons', 'catalog.json');
const outputPath = path.join(root, 'renderers', 'shared', 'generated-domain-icons.mjs');
const lucideRoot = path.join(root, 'node_modules', 'lucide-static');
const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
const lucideVersion = JSON.parse(fs.readFileSync(path.join(lucideRoot, 'package.json'), 'utf8')).version;

const SHAPES = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const GEOMETRY = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points']);

function fail(message) {
  console.error(`domain icons: ${message}`);
  process.exit(1);
}

// Keep only geometry. Presentation (stroke, fill, colour) belongs to the
// renderer's semantic-sigil styling so icons follow the node's theme tokens.
function iconBody(name) {
  const file = path.join(lucideRoot, 'icons', `${name}.svg`);
  if (!fs.existsSync(file)) fail(`lucide-static ${lucideVersion} has no icon "${name}"`);
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
  const elements = [...inner.matchAll(/<([a-z]+)\b([^>]*?)\/?>/g)];
  if (!elements.length) fail(`icon "${name}" has no drawable elements`);
  return elements.map(([, tag, rawAttrs]) => {
    if (!SHAPES.has(tag)) fail(`icon "${name}" uses unsupported element <${tag}>`);
    const attrs = [...rawAttrs.matchAll(/([a-z0-9-]+)="([^"]*)"/g)].map(([, key, value]) => {
      if (!GEOMETRY.has(key)) fail(`icon "${name}" <${tag}> carries non-geometry attribute ${key}`);
      if (!/^[-0-9a-zA-Z .,]*$/.test(value)) fail(`icon "${name}" <${tag}> ${key} has unexpected characters`);
      return `${key}="${value}"`;
    });
    return `<${tag} ${attrs.join(' ')}/>`;
  }).join('');
}

if (catalog.schemaVersion !== 1 || !Array.isArray(catalog.icons) || !catalog.icons.length) {
  fail('catalog.json must contain a non-empty schemaVersion 1 icons array');
}
const seen = new Map();
const icons = catalog.icons.map((entry, index) => {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.id || '')) fail(`icons[${index}] has an invalid id`);
  if (!entry.title || !entry.use || !entry.lucide) fail(`icons[${index}] ${entry.id} needs title, use and lucide`);
  const aliases = [...new Set((entry.aliases || []).map((alias) => String(alias).trim().toLowerCase()).filter(Boolean))];
  for (const key of [entry.id, ...aliases]) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(key)) fail(`${entry.id} alias "${key}" must be lowercase dash-case`);
    if (seen.has(key)) fail(`"${key}" is claimed by both ${seen.get(key)} and ${entry.id}`);
    seen.set(key, entry.id);
  }
  return { id: entry.id, title: entry.title, use: entry.use, aliases, lucide: entry.lucide, body: iconBody(entry.lucide) };
});

const banner = '// Generated by scripts/generate-domain-icons.mjs. Do not edit by hand.\n'
  + `// Icon geometry from lucide-static ${lucideVersion} (ISC); see domain-icons/LICENSE-lucide.txt.\n\n`;
const generated = `${banner}export const DOMAIN_ICON_SOURCE = Object.freeze(${JSON.stringify({
  provider: 'Lucide',
  package: 'lucide-static',
  version: lucideVersion,
  license: 'ISC',
  url: 'https://lucide.dev',
})});\n\nexport const DOMAIN_ICONS = Object.freeze([\n${icons.map((icon) => `  Object.freeze(${JSON.stringify(icon)}),`).join('\n')}\n]);\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== generated) {
    console.error('generated domain icons are stale — run npm run generate:domain-icons');
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`generated ${path.relative(root, outputPath)} (${icons.length} icons)`);
}
